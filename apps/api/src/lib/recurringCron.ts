import { prisma } from './prisma.js';
import { logger } from './logger.js';
import { RecurringFrequency } from '@nimu/shared';

export function calculateNextRun(fromDate: Date, frequency: RecurringFrequency): Date {
  const next = new Date(fromDate);
  switch (frequency) {
    case 'daily':
      next.setDate(next.getDate() + 1);
      break;
    case 'weekly':
      next.setDate(next.getDate() + 7);
      break;
    case 'monthly':
      next.setMonth(next.getMonth() + 1);
      break;
    case 'yearly':
      next.setFullYear(next.getFullYear() + 1);
      break;
  }
  return next;
}

export interface ProcessRecurringResult {
  processedRules: number;
  createdTransactions: number;
}

/**
 * Searches for all recurring rules where nextRunAt <= current time,
 * generates transactions for each due period, and advances nextRunAt.
 */
export async function processDueRecurringRules(now = new Date()): Promise<ProcessRecurringResult> {
  logger.info({ now }, 'Running recurring rules cron processor');

  const dueRules = await prisma.recurringRule.findMany({
    where: {
      nextRunAt: { lte: now },
    },
  });

  let createdTransactions = 0;

  for (const rule of dueRules) {
    const template = rule.template as {
      type: 'expense' | 'income';
      amountMinor: number;
      category: string;
      description: string;
      paymentMethod?: string;
      notes?: string;
    };

    let nextRun = new Date(rule.nextRunAt);

    // If nextRun is significantly in the past, process in steps up to now (max 12 iterations to avoid infinite loops)
    let iterations = 0;
    while (nextRun <= now && iterations < 12) {
      await prisma.transaction.create({
        data: {
          userId: rule.userId,
          type: template.type,
          amountMinor: template.amountMinor,
          category: template.category,
          description: template.description,
          paymentMethod: template.paymentMethod || 'upi',
          notes: template.notes || 'Generated by recurring rule',
          date: nextRun,
          isRecurring: true,
          recurringRuleId: rule.id,
        },
      });

      createdTransactions++;
      iterations++;
      nextRun = calculateNextRun(nextRun, rule.frequency as RecurringFrequency);
    }

    // Update rule with new nextRunAt
    await prisma.recurringRule.update({
      where: { id: rule.id },
      data: { nextRunAt: nextRun },
    });
  }

  const result = {
    processedRules: dueRules.length,
    createdTransactions,
  };

  logger.info(result, 'Completed recurring rules cron processing');
  return result;
}
